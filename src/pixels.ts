import type Phaser from 'phaser';

// Tiny diagnostic font made of rectangles. No font download or smoothing.
const glyphs: Record<string, string> = {
  A:'010101111101101', B:'110101110101110', C:'111100100100111',
  D:'110101101101110', E:'111100110100111', F:'111100110100100',
  G:'111100101101111', H:'101101111101101', I:'111010010010111',
  J:'001001001101111', K:'101101110101101', L:'100100100100111',
  M:'101111111101101', N:'101111111111101', O:'111101101101111',
  P:'110101110100100', Q:'111101101111001', R:'110101110101101',
  S:'111100111001111', T:'111010010010010', U:'101101101101111',
  V:'101101101101010', W:'101101111111101', X:'101101010101101',
  Y:'101101010010010', Z:'111001010100111',
  '0':'111101101101111', '1':'010110010010111', '2':'111001111100111',
  '3':'111001111001111', '4':'101101111001001', '5':'111100111001111',
  '6':'111100111101111', '7':'111001010010010', '8':'111101111101111',
  '9':'111101111001111', '/':'001001010100100', '-':'000000111000000',
};

export function pixelText(g: Phaser.GameObjects.Graphics, text: string, x: number, y: number, color: number) {
  g.fillStyle(color);
  [...text].forEach((char, index) => {
    const bits = glyphs[char];
    if (!bits) return;
    for (let p = 0; p < bits.length; p++) if (bits[p] === '1') g.fillRect(x + index * 4 + p % 3, y + Math.floor(p / 3), 1, 1);
  });
}
